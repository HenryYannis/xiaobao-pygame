import pygame

pygame.init()
窗口 = pygame.display.set_mode((300, 300))
pygame.display.set_caption("Tic-Tac-Toe - Lesson 3")
时钟 = pygame.time.Clock()
字体 = pygame.font.Font(None, 36)                     # 新增变量：纯内置默认字体(是什么)，避免跨平台字体报错(为什么)，字号36(怎么用)

棋盘数据 = [0] * 9                                     # 棋盘数据模型：长度为9的一维列表，0代表空，1代表玩家1，2代表玩家2
当前玩家 = 1                                           # 执子标志位：1代表玩家1，2代表玩家2(交替落子)
获胜玩家 = 0                                           # 新增变量：记录获胜者编号(0未结束，1玩家1胜，2玩家2胜)
运行中 = True

def 检查获胜():                                       # 新增函数：比对8种三连线获胜组合
    获胜线列表 = [
        [0, 1, 2], [3, 4, 5], [6, 7, 8],              # 横向三行
        [0, 3, 6], [1, 4, 7], [2, 5, 8],              # 纵向三列
        [0, 4, 8], [2, 4, 6]                          # 对角线两条
    ]
    for 甲, 乙, 丙 in 获胜线列表:
        if 棋盘数据[甲] != 0 and 棋盘数据[甲] == 棋盘数据[乙] == 棋盘数据[丙]:
            return 棋盘数据[甲]                        # 返回获胜的玩家编号(1或2)
    return 0

while 运行中:
    for 事件 in pygame.event.get():
        if 事件.type == pygame.QUIT:
            运行中 = False
        if 获胜玩家 != 0 or 0 not in 棋盘数据:        # 新增代码：当出现胜者或棋盘填满平局时支持按空格重开
            if 事件.type == pygame.KEYDOWN and 事件.key == pygame.K_SPACE:
                棋盘数据 = [0] * 9                     # 新增代码：清空棋盘所有格子
                当前玩家 = 1                           # 新增代码：重置玩家1先手
                获胜玩家 = 0                           # 新增代码：重置胜负状态

        if 获胜玩家 == 0 and 事件.type == pygame.MOUSEBUTTONDOWN:
            鼠标x, 鼠标y = pygame.mouse.get_pos()
            格点索引 = (鼠标y // 100) * 3 + (鼠标x // 100)  # 坐标换算：根据光标所在行列换算对应的一维列表索引(0-8)
            if 0 <= 格点索引 < 9 and 棋盘数据[格点索引] == 0:
                棋盘数据[格点索引] = 当前玩家         # 在空位落子填入当前玩家编号
                获胜玩家 = 检查获胜()                  # 新增代码：每次落子后立即执行胜负判定
                当前玩家 = 2 if 当前玩家 == 1 else 1   # 切换执子方：1与2交替轮换

    窗口.fill((255, 255, 255))                         # 纯白背景全屏填充

    for 序号 in range(1, 3):                           # 绘制九宫格四条黑色分割网格线
        pygame.draw.line(窗口, (0, 0, 0), (序号 * 100, 0), (序号 * 100, 300), 2)    # 纵向竖线
        pygame.draw.line(窗口, (0, 0, 0), (0, 序号 * 100), (300, 序号 * 100), 2)    # 横向水平线

    for 索引, 棋子 in enumerate(棋盘数据):             # 遍历棋盘数据绘制双方棋子
        中心x = (索引 % 3) * 100 + 50
        中心y = (索引 // 3) * 100 + 50
        if 棋子 == 1:
            pygame.draw.circle(窗口, (255, 60, 60), (中心x, 中心y), 30, 3)          # 玩家1：绘制红色空心圆圈(半径30, 线宽3)
        elif 棋子 == 2:
            pygame.draw.rect(窗口, (50, 120, 255), (中心x - 25, 中心y - 25, 50, 50), 3) # 玩家2：绘制蓝色空心正方形(边长50, 线宽3)

    if 获胜玩家 != 0:                                  # 新增代码：获胜结算纯英文文字呈现
        提示文本 = f"PLAYER {获胜玩家} WINS!"
        提示画面 = 字体.render(提示文本, True, (0, 180, 50))
        窗口.blit(提示画面, (45, 135))
    elif 0 not in 棋盘数据:                            # 新增代码：棋盘填满且无胜者时显示平局
        提示画面 = 字体.render("DRAW - Press SPACE", True, (150, 150, 150))
        窗口.blit(提示画面, (25, 135))

    pygame.display.flip()                              # 双缓冲刷新：将新绘制的画面一次性呈现到屏幕
    时钟.tick(60)                                      # 锁定帧率：稳定每秒60帧流畅运行

pygame.quit()
