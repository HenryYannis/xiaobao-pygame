import pygame, random, math

pygame.init()
窗口 = pygame.display.set_mode((400, 400))
pygame.display.set_caption("Whac-A-Mole - Lesson 3")
时钟 = pygame.time.Clock()
字体 = pygame.font.Font(None, 36)                     # 新增变量：纯内置默认字体(是什么)，杜绝系统属性避免跨平台报错(为什么)，字号36(怎么用)

得分 = 0                                              # 新增变量：累计命中得分
倒计时秒数 = 15                                       # 新增变量：游戏限时总秒数
开始时间 = pygame.time.get_ticks()                    # 新增变量：本局开始的毫秒时间戳，重开时刷新它，倒计时才会重新开始
剩余时间 = 倒计时秒数
地洞列表 = []
for 行 in range(3):
    for 列 in range(3):
        地洞列表.append([列 * 120 + 80, 行 * 120 + 80])     # 九宫格网格：计算9个地洞的圆心坐标(x, y)

地鼠索引 = -1                                         # 地鼠状态：当前冒头的洞口编号，-1表示潜伏隐藏
下次冒头时间 = 0                                      # 刷新时刻：下一次更换洞口冒头的毫秒时间戳
运行中 = True

while 运行中:
    当前时间 = pygame.time.get_ticks()                 # 获取毫秒：获取游戏自启动以来的时间戳

    for 事件 in pygame.event.get():
        if 事件.type == pygame.QUIT:
            运行中 = False
        if 事件.type == pygame.MOUSEBUTTONDOWN and 事件.button == 1 and 剩余时间 > 0 and 地鼠索引 != -1:  # 新增代码：时间未结束且有地鼠冒头时响应左键
            鼠标x, 鼠标y = 事件.pos                   # 取事件自带的点击坐标
            地鼠x, 地鼠y = 地洞列表[地鼠索引]
            if math.hypot(鼠标x - 地鼠x, 鼠标y - 地鼠y) <= 30: # 命中判定：勾股定理计算点击点到地鼠圆心距离，小于半径30判定击中
                地鼠索引 = -1                         # 击中缩回：地鼠被打中后立刻隐藏
                下次冒头时间 = 当前时间 + 500         # 节奏加快：缩短等待时间，500毫秒后再次冒头
                得分 += 10                            # 新增代码：命中加分奖励，每次击中加10分
        if 事件.type == pygame.KEYDOWN and 事件.key == pygame.K_SPACE and 剩余时间 <= 0:  # 新增代码：时间到后按空格重开
            得分 = 0                                  # 新增代码：分数清零
            开始时间 = 当前时间                       # 新增代码：重新记录开始时间，倒计时从15秒重新开始
            剩余时间 = 倒计时秒数                     # 新增代码：剩余时间恢复满格
            下次冒头时间 = 0                          # 新增代码：地鼠马上重新冒头

    已运行秒数 = (当前时间 - 开始时间) // 1000        # 新增代码：本局已过的毫秒整除1000换算为秒数
    剩余时间 = max(0, 倒计时秒数 - 已运行秒数)         # 新增代码：计算剩余时间，max防止出现负数

    if 剩余时间 > 0:                                   # 新增代码：时间未结束时保持正常冒头逻辑
        if 当前时间 > 下次冒头时间:                   # 定时切换：当前时间超过预定时刻，地鼠随机换洞冒头
            地鼠索引 = random.randint(0, 8)           # 随机选洞：从9个地洞(0-8)中随机抽取一个
            下次冒头时间 = 当前时间 + 1000            # 预设间隔：设定1000毫秒(1秒)后再次切换
    else:
        地鼠索引 = -1                                 # 新增代码：时间到后地鼠全部隐藏不再出现

    窗口.fill((34, 139, 34))                           # 草地背景：RGB绿色(34, 139, 34)全屏填充
    for 编号, 坐标 in enumerate(地洞列表):             # 遍历地洞：依次获取每个地洞的编号索引与坐标
        pygame.draw.circle(窗口, (50, 25, 0), 坐标, 40)       # 绘制地洞：深褐色实心圆(半径40)
        if 编号 == 地鼠索引:
            pygame.draw.circle(窗口, (200, 150, 100), 坐标, 30) # 绘制地鼠：浅褐色实心圆(半径30)

    得分画面 = 字体.render(f"SCORE: {得分}", True, (255, 255, 255))       # 新增代码：默认字体纯英文渲染当前得分图像(白色)
    窗口.blit(得分画面, (10, 10))                                         # 新增代码：贴在左上角UI位置(10, 10)
    时间画面 = 字体.render(f"TIME: {剩余时间}s", True, (255, 0, 0))       # 新增代码：醒目红色渲染剩余时间
    窗口.blit(时间画面, (270, 10))                                        # 新增代码：贴在右上角UI位置(270, 10)

    if 剩余时间 <= 0:
        提示画面 = 字体.render("TIME UP! - Press SPACE", True, (255, 255, 0))  # 新增代码：时间耗尽黄色大字提示，并提示按空格重开
        窗口.blit(提示画面, 提示画面.get_rect(center=(200, 200)))  # 新增代码：get_rect(center=...)让文字正好居中在窗口中央

    pygame.display.flip()                              # 双缓冲刷新：将新绘制的画面一次性呈现到屏幕
    时钟.tick(60)                                      # 锁定帧率：稳定每秒60帧流畅运行

pygame.quit()
