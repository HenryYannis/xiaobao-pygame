import pygame

pygame.init()
窗口 = pygame.display.set_mode((400, 400))
pygame.display.set_caption("Breakout - Lesson 4")
时钟 = pygame.time.Clock()
字体 = pygame.font.Font(None, 36)                     # 新增变量：创建纯内置默认字体(是什么)，避免跨平台字体报错(为什么)，字号36(怎么用)

砖块列表 = []
for 行 in range(4):
    for 列 in range(5):
        砖块列表.append([列 * 70 + 30, 行 * 30 + 40, 60, 20])

球 = [200, 200]
速度 = [3, -3]
得分 = 0                                              # 新增变量：击碎砖块累计得分
运行中 = True

while 运行中:
    for 事件 in pygame.event.get():
        if 事件.type == pygame.QUIT:
            运行中 = False

    挡板x = max(50, min(350, pygame.mouse.get_pos()[0]))  # 挡板跟随鼠标横向滑动，并在左右边缘限位(宽度100)

    球[0] += 速度[0]                                  # 更新小球水平位移
    球[1] += 速度[1]                                  # 更新小球垂直位移

    if 球[0] <= 10 or 球[0] >= 390:                   # 左右墙壁碰撞：水平速度取反反弹
        速度[0] *= -1
    if 球[1] <= 10:                                   # 顶部天花板碰撞：垂直速度取反向下
        速度[1] = abs(速度[1])

    if 球[1] >= 360 and 挡板x - 50 <= 球[0] <= 挡板x + 50:  # 挡板接球判定：小球到达挡板高度并在挡板100像素宽度内
        球[1] = 359
        速度[1] = -abs(速度[1])

    for 索引, 砖块 in enumerate(砖块列表):             # 新增代码：遍历砖块列表进行矩形碰撞检测
        if 砖块[0] <= 球[0] <= 砖块[0] + 砖块[2] and 砖块[1] <= 球[1] <= 砖块[1] + 砖块[3]:  # 新增代码：球心落在砖块区域内判定命中
            砖块列表.pop(索引)                         # 新增代码：击中后安全移除该砖块
            速度[1] *= -1                             # 新增代码：小球垂直速度取反反弹
            得分 += 10                                # 新增代码：击碎砖块累加10分
            break                                     # 新增代码：单次碰撞只击碎一块砖

    if 球[1] > 400:                                   # 漏接重置：小球掉出底部后重新发球
        球 = [200, 200]
        速度 = [3, -3]

    窗口.fill((20, 20, 20))                           # 暗色背景全屏填充覆盖
    pygame.draw.circle(窗口, (255, 255, 255), (int(球[0]), int(球[1])), 10)  # 绘制白色小球(圆心, 半径10)
    pygame.draw.rect(窗口, (0, 255, 120), (挡板x - 50, 370, 100, 10))        # 绘制翠绿色挡板(宽100, 高10)

    for 砖块 in 砖块列表:
        pygame.draw.rect(窗口, (255, 160, 40), 砖块)

    得分画面 = 字体.render(f"SCORE: {得分}", True, (255, 255, 255))           # 新增代码：默认字体纯英文渲染得分看板
    窗口.blit(得分画面, (10, 10))                                              # 新增代码：贴在左上角UI位置

    pygame.display.flip()                              # 双缓冲刷新：将新绘制的画面一次性呈现到屏幕
    时钟.tick(60)                                      # 锁定帧率：稳定每秒60帧流畅运行

pygame.quit()
