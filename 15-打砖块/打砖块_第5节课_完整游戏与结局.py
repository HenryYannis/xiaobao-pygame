import pygame

pygame.init()
窗口 = pygame.display.set_mode((400, 400))
pygame.display.set_caption("Breakout - Lesson 5")
时钟 = pygame.time.Clock()
字体 = pygame.font.Font(None, 36)                     # 创建纯内置默认字体(是什么)，避免跨平台字体报错(为什么)，字号36(怎么用)

砖块行颜色 = [                                         # 新增变量：不同行砖块的区分颜色(红、橙、黄、绿)
    (255, 60, 60),
    (255, 160, 40),
    (255, 220, 40),
    (60, 220, 60)
]

def 初始化砖块():                                     # 新增函数：生成4行5列的砖块网格列表
    列表 = []
    for 行 in range(4):
        for 列 in range(5):
            列表.append([列 * 70 + 30, 行 * 30 + 40, 60, 20, 行])  # 存储[x, y, 宽度60, 高度20, 行号]
    return 列表

砖块列表 = 初始化砖块()
球 = [200, 250]                                       # 小球当前坐标[x, y]
速度 = [3, -3]                                        # 小球当前水平与垂直速度[vx, vy]
得分 = 0                                              # 累计击碎砖块得分
游戏状态 = "进行中"                                   # 新增变量：记录当前局状态("进行中"、"胜利"、"失败")
运行中 = True

while 运行中:
    for 事件 in pygame.event.get():
        if 事件.type == pygame.QUIT:
            运行中 = False
        if 游戏状态 != "进行中" and 事件.type == pygame.KEYDOWN and 事件.key == pygame.K_SPACE:  # 新增代码：结局后按空格重开
            砖块列表 = 初始化砖块()                   # 新增代码：重置所有砖块
            球 = [200, 250]                           # 新增代码：重置小球位置
            速度 = [3, -3]                            # 新增代码：重置小球速度
            得分 = 0                                  # 新增代码：重置分数为0
            游戏状态 = "进行中"                       # 新增代码：重置状态为进行中

    if 游戏状态 == "进行中":                           # 新增代码：仅在进行中更新物理碰撞与移动
        挡板x = max(50, min(350, pygame.mouse.get_pos()[0]))  # 挡板跟随鼠标横向滑动，并在左右边缘限位(宽度100)

        球[0] += 速度[0]                              # 更新小球水平位移
        球[1] += 速度[1]                              # 更新小球垂直位移

        if 球[0] <= 10 or 球[0] >= 390:               # 左右墙壁碰撞：水平速度取反反弹
            速度[0] *= -1
        if 球[1] <= 10:                               # 顶部天花板碰撞：垂直速度取反向下
            速度[1] = abs(速度[1])

        if 速度[1] > 0 and 360 <= 球[1] <= 375 and 挡板x - 50 <= 球[0] <= 挡板x + 50:  # 挡板接球判定：小球到达挡板高度并在挡板100像素宽度内；还要求球正在下落且没掉过挡板
            球[1] = 359                               # 位置微调修正，防止球卡在板内
            速度[1] = -abs(速度[1])                   # 向上弹起：确保垂直速度为负数
            速度[0] = (球[0] - 挡板x) / 10            # 击中挡板的位置决定反弹角度：打在中间直直向上，越靠边斜得越厉害(-5到5)

        球矩形 = pygame.Rect(球[0] - 10, 球[1] - 10, 20, 20)  # 小球的外接正方形(边长20)，把半径10也算进碰撞范围
        for 索引, 砖块 in enumerate(砖块列表):        # 遍历砖块列表进行矩形碰撞检测
            砖块矩形 = pygame.Rect(砖块[0], 砖块[1], 砖块[2], 砖块[3])
            if 球矩形.colliderect(砖块矩形):          # colliderect判断两个矩形是否有重叠，球边一碰到砖就算命中
                砖块列表.pop(索引)                     # 击碎消除：将击中的砖块从列表中安全移除
                重叠 = 球矩形.clip(砖块矩形)          # clip取出两个矩形重叠的那一小块
                if 重叠.width < 重叠.height:          # 重叠区域又高又窄：说明是从砖块左右侧面撞上的
                    速度[0] *= -1                     # 侧面撞击：水平速度取反
                else:                                 # 重叠区域又宽又扁：说明是从砖块上下面撞上的
                    速度[1] *= -1                     # 上下撞击：垂直速度取反
                得分 += 10                            # 击碎加分：每块砖奖励累加10分
                break

        if len(砖块列表) == 0:                         # 新增代码：所有砖块击碎完毕判定获胜
            游戏状态 = "胜利"
        elif 球[1] >= 390:                             # 新增代码：小球漏接掉出屏幕底边判定失败
            游戏状态 = "失败"

    窗口.fill((20, 20, 20))                           # 暗色背景全屏填充覆盖
    pygame.draw.circle(窗口, (255, 255, 255), (int(球[0]), int(球[1])), 10)  # 绘制白色小球(圆心, 半径10)
    pygame.draw.rect(窗口, (0, 255, 120), (挡板x - 50, 370, 100, 10))        # 绘制翠绿色挡板(宽100, 高10)

    for 砖块 in 砖块列表:                              # 绘制剩余活动砖块
        颜色 = 砖块行颜色[砖块[4]]                    # 新增代码：依据行号提取对应的行区分色彩
        pygame.draw.rect(窗口, 颜色, (砖块[0], 砖块[1], 砖块[2], 砖块[3]))

    得分画面 = 字体.render(f"SCORE: {得分}", True, (255, 255, 255))           # 默认字体渲染纯英文得分看板
    窗口.blit(得分画面, (10, 10))

    if 游戏状态 == "胜利":                             # 新增代码：通关胜利纯英文提示
        提示画面 = 字体.render("YOU WIN! - Press SPACE", True, (60, 220, 60))
        窗口.blit(提示画面, 提示画面.get_rect(center=(200, 200)))  # get_rect(center=...)让文字正好居中
    elif 游戏状态 == "失败":                           # 新增代码：触底失败纯英文提示
        提示画面 = 字体.render("GAME OVER - Press SPACE", True, (255, 60, 60))
        窗口.blit(提示画面, 提示画面.get_rect(center=(200, 200)))  # get_rect(center=...)让文字正好居中

    pygame.display.flip()                              # 双缓冲刷新：将新绘制的画面一次性呈现到屏幕
    时钟.tick(60)                                      # 锁定帧率：稳定每秒60帧流畅运行

pygame.quit()
