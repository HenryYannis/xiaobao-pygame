import pygame

pygame.init()
窗口 = pygame.display.set_mode((400, 400))
pygame.display.set_caption("Breakout - Lesson 2")
时钟 = pygame.time.Clock()

球 = [200, 200]                                       # 小球当前坐标[x, y]
速度 = [3, -3]                                        # 小球当前水平与垂直速度[vx, vy]
运行中 = True

while 运行中:
    for 事件 in pygame.event.get():
        if 事件.type == pygame.QUIT:
            运行中 = False

    挡板x = max(50, min(350, pygame.mouse.get_pos()[0]))  # 新增代码：挡板跟随鼠标横向滑动，并在左右边缘限位(宽度100)

    球[0] += 速度[0]                                  # 更新小球水平位移
    球[1] += 速度[1]                                  # 更新小球垂直位移

    if 球[0] <= 10 or 球[0] >= 390:                   # 左右墙壁碰撞：水平速度取反反弹
        速度[0] *= -1
    if 球[1] <= 10:                                   # 顶部天花板碰撞：垂直速度取反向下
        速度[1] = abs(速度[1])

    if 速度[1] > 0 and 360 <= 球[1] <= 375 and 挡板x - 50 <= 球[0] <= 挡板x + 50:  # 新增代码：挡板接球判定(小球到达挡板高度并在挡板100像素宽度内)；还要求球正在下落且没掉过挡板
        球[1] = 359                                   # 新增代码：位置微调修正，防止球卡在板内
        速度[1] = -abs(速度[1])                       # 新增代码：向上弹起，确保垂直速度为负数
        速度[0] = (球[0] - 挡板x) / 10                # 新增代码：击中挡板的位置决定反弹角度：打在中间直直向上，越靠边斜得越厉害(-5到5)

    if 球[1] > 400:                                   # 漏接重置：小球掉出底部后重新发球
        球 = [200, 200]
        速度 = [3, -3]

    窗口.fill((20, 20, 20))                           # 暗色背景全屏填充覆盖
    pygame.draw.circle(窗口, (255, 255, 255), (int(球[0]), int(球[1])), 10)  # 绘制白色小球(圆心, 半径10)
    pygame.draw.rect(窗口, (0, 255, 120), (挡板x - 50, 370, 100, 10))        # 新增代码：绘制翠绿色挡板(宽100, 高10)

    pygame.display.flip()                              # 双缓冲刷新：将新绘制的画面一次性呈现到屏幕
    时钟.tick(60)                                      # 锁定帧率：稳定每秒60帧流畅运行

pygame.quit()
