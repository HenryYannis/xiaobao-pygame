import pygame, random

pygame.init()
窗口 = pygame.display.set_mode((400, 300))
pygame.display.set_caption("Color Match - Lesson 3")
时钟 = pygame.time.Clock()
字体 = pygame.font.Font(None, 36)                     # 创建纯内置默认字体(是什么)，避免跨平台字体报错(为什么)，字号36(怎么用)

颜色列表 = [
    (255, 50, 50),                                    # 鲜红色
    (50, 200, 50),                                    # 翠绿色
    (50, 120, 255),                                   # 天蓝色
    (255, 200, 30),                                   # 明黄色
    (200, 50, 220)                                    # 紫罗兰色
]

def 生成题目():                                       # 题库生成函数：随机抽取两个互不相同的备选颜色并指定目标
    选色1, 选色2 = random.sample(range(len(颜色列表)), 2)
    正确答案 = random.choice([选色1, 选色2])
    return 选色1, 选色2, 正确答案

选项1, 选项2, 目标答案 = 生成题目()
得分 = 0                                              # 新增变量：累计匹配成功的得分
剩余时间比例 = 1.0                                     # 新增变量：时间条百分比(1.0代表满槽，随时间逐渐缩短)
游戏结束 = False                                      # 新增变量：时间耗尽后的结局标志位
运行中 = True

while 运行中:
    for 事件 in pygame.event.get():
        if 事件.type == pygame.QUIT:
            运行中 = False
        if 游戏结束 and 事件.type == pygame.KEYDOWN and 事件.key == pygame.K_SPACE:  # 新增代码：超时失败后按空格键满血重开
            得分 = 0                                  # 新增代码：分数清零
            剩余时间比例 = 1.0                         # 新增代码：时间条恢复满槽
            选项1, 选项2, 目标答案 = 生成题目()         # 新增代码：重置题目
            游戏结束 = False                          # 新增代码：恢复游戏进行态

        if not 游戏结束 and 事件.type == pygame.MOUSEBUTTONDOWN:
            鼠标x, 鼠标y = pygame.mouse.get_pos()
            选择颜色 = -1                             # 初始化选择结果，-1代表未点击在有效方块内
            if 160 <= 鼠标y <= 240:                    # 判定是否落在下方选项高度区间内
                if 50 <= 鼠标x <= 170:                 # 点击左侧选项方块
                    选择颜色 = 选项1
                elif 230 <= 鼠标x <= 350:              # 点击右侧选项方块
                    选择颜色 = 选项2

            if 选择颜色 == 目标答案:                  # 颜色比对：点击的颜色与目标一致判定答对
                得分 += 10                            # 新增代码：答对加10分
                剩余时间比例 = min(1.0, 剩余时间比例 + 0.25)  # 新增代码：答对奖励补充时间条(上限1.0)
                选项1, 选项2, 目标答案 = 生成题目()     # 立即刷新下一轮题目

    if not 游戏结束:                                   # 新增代码：仅在进行中递减时间进度
        剩余时间比例 -= 0.004                         # 新增代码：时间自然流逝，每帧匀速减少时间
        if 剩余时间比例 <= 0.0:                        # 新增代码：时间耗尽触发游戏结束
            剩余时间比例 = 0.0
            游戏结束 = True

    窗口.fill((255, 255, 255))                         # 纯白背景全屏清屏覆盖
    pygame.draw.rect(窗口, (255, 60, 60), (0, 0, int(400 * 剩余时间比例), 8))  # 新增代码：顶部红色倒计时进度条(宽=400*比例)

    目标标题 = 字体.render("TARGET", True, (80, 80, 80))
    窗口.blit(目标标题, (150, 20))                    # 绘制顶部英文目标提示
    pygame.draw.rect(窗口, 颜色列表[目标答案], (150, 60, 100, 50))              # 绘制目标颜色矩形(宽100, 高50)

    pygame.draw.rect(窗口, 颜色列表[选项1], (50, 160, 120, 80))                 # 绘制左侧候选颜色方块(宽120, 高80)
    pygame.draw.rect(窗口, 颜色列表[选项2], (230, 160, 120, 80))                # 绘制右侧候选颜色方块(宽120, 高80)

    得分画面 = 字体.render(f"SCORE: {得分}", True, (0, 0, 0))                   # 新增代码：默认字体纯英文渲染得分
    窗口.blit(得分画面, (10, 15))                                              # 新增代码：贴在左上角UI位置

    if 游戏结束:
        提示画面 = 字体.render("TIME UP! - Press SPACE", True, (255, 0, 0))      # 新增代码：红色醒目英文提示时间耗尽与空格重开
        窗口.blit(提示画面, (50, 120))                                          # 新增代码：居中贴在画面中部

    pygame.display.flip()                              # 双缓冲刷新：将新绘制的画面一次性呈现到屏幕
    时钟.tick(60)                                      # 锁定帧率：稳定每秒60帧流畅运行

pygame.quit()
