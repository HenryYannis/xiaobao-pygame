import pygame

pygame.init()
窗口 = pygame.display.set_mode((600, 300))
pygame.display.set_caption("Dino Run - Lesson 3")
时钟 = pygame.time.Clock()
字体 = pygame.font.Font(None, 36)                     # 新增变量：纯内置默认字体(是什么)，避免跨平台字体报错(为什么)，字号36(怎么用)

地面y = 250                                           # 地面水平基准线高度
恐龙x = 100                                           # 恐龙水平固定位置
恐龙y = 200.0                                         # 恐龙垂直坐标(40x50大小，站立时y为200)
速度y = 0.0                                           # 恐龙垂直移动速度
重力 = 0.8                                            # 重力加速度
障碍物 = pygame.Rect(600, 210, 30, 40)                # 新增变量：仙人掌障碍物矩形对象(初始在屏幕右侧外)
得分 = 0                                              # 新增变量：成功越过障碍物的累计得分
游戏结束 = False                                      # 新增变量：标记当前是否发生撞击失败
运行中 = True

while 运行中:
    for 事件 in pygame.event.get():
        if 事件.type == pygame.QUIT:
            运行中 = False
        if 事件.type == pygame.KEYDOWN and 事件.key == pygame.K_SPACE:
            if 游戏结束:                               # 新增代码：失败状态下按空格重置开局
                恐龙y = 200.0                         # 新增代码：重置恐龙位置
                速度y = 0.0                           # 新增代码：重置速度
                障碍物.x = 600                        # 新增代码：重置仙人掌位置
                得分 = 0                              # 新增代码：重置得分
                游戏结束 = False                      # 新增代码：恢复进行中状态
            elif 恐龙y >= 200:                         # 仅在恐龙着地时允许跳跃，防止空中二段跳
                速度y = -14.0                         # 施加向上的初始起跳速度

    if not 游戏结束:                                   # 新增代码：仅在游戏未结束时更新运动与障碍
        速度y += 重力                                 # 速度受重力持续作用向下增加
        恐龙y += 速度y                                # 更新垂直位移
        if 恐龙y > 200:                               # 触地判定：踩在地面上不再下陷
            恐龙y = 200
            速度y = 0.0

        障碍物.x -= 8                                 # 新增代码：仙人掌向左匀速移动滚动，制造奔跑感
        if 障碍物.right < 0:                          # 新增代码：仙人掌完全移出屏幕左侧边界
            障碍物.x = 600                            # 新增代码：重置回屏幕右侧外重新滚入
            得分 += 1                                 # 新增代码：成功跳跃越过障碍物，得分加1分

        恐龙矩形 = pygame.Rect(恐龙x, int(恐龙y), 40, 50)  # 新增代码：生成恐龙当前位置的碰撞包围盒
        if 恐龙矩形.colliderect(障碍物):              # 新增代码：检测恐龙与仙人掌矩形是否发生重叠碰撞
            游戏结束 = True                           # 新增代码：撞击障碍物触发游戏结束

    窗口.fill((255, 255, 255))                         # 纯白背景全屏覆盖
    pygame.draw.rect(窗口, (200, 200, 200), (0, 地面y, 600, 50))       # 绘制浅灰色平整地面(高50)
    pygame.draw.rect(窗口, (67, 160, 72), (恐龙x, int(恐龙y), 40, 50))  # 绘制翠绿色小恐龙方块(宽40, 高50)
    pygame.draw.rect(窗口, (220, 50, 50), 障碍物)                      # 新增代码：绘制红色仙人掌障碍物矩形

    得分画面 = 字体.render(f"SCORE: {得分}", True, (0, 0, 0))          # 新增代码：默认字体纯英文渲染得分看板
    窗口.blit(得分画面, (10, 10))

    if 游戏结束:
        提示画面 = 字体.render("GAME OVER - Press SPACE", True, (220, 50, 50))  # 新增代码：红色醒目英文提示失败与按空格重开
        窗口.blit(提示画面, (120, 100))                                      # 新增代码：居中贴在画面中部

    pygame.display.flip()                              # 双缓冲刷新：将新绘制的画面一次性呈现到屏幕
    时钟.tick(60)                                      # 锁定帧率：稳定每秒60帧流畅运行

pygame.quit()
