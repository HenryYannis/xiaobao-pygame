import pygame

pygame.init()
窗口 = pygame.display.set_mode((400, 460))
pygame.display.set_caption("Pixel Painter - Lesson 3")
时钟 = pygame.time.Clock()

画布 = [[0 for _ in range(10)] for _ in range(10)]     # 二维画布数据：10行10列网格，存储每个格子的颜色编号(初始全为0白色)
调色盘颜色 = [                                         # 新增变量：调色盘支持的5种绘制颜色列表
    (255, 255, 255),                                  # 0号：橡皮擦白色
    (0, 0, 0),                                        # 1号：经典墨黑色
    (255, 60, 60),                                    # 2号：活力鲜红色
    (50, 200, 50),                                    # 3号：自然翠绿色
    (50, 120, 255)                                    # 4号：晴空天蓝色
]
当前颜色索引 = 1                                       # 新增变量：当前画笔选中的颜色编号(初始默认使用1号黑色)
运行中 = True

while 运行中:
    for 事件 in pygame.event.get():
        if 事件.type == pygame.QUIT:
            运行中 = False
        if 事件.type == pygame.MOUSEBUTTONDOWN and 事件.button == 3:  # 新增代码：监听鼠标右键点击执行一键清空画布
            画布 = [[0 for _ in range(10)] for _ in range(10)]       # 新增代码：将10x10全部格子重置为0号白色

    if pygame.mouse.get_pressed()[0]:                  # 监听鼠标左键按住状态，支持连续画线涂色
        鼠标x, 鼠标y = pygame.mouse.get_pos()
        if 鼠标y < 400:                                # 画布区域点击：光标在上方400x400画布范围内
            列 = 鼠标x // 40                           # 索引换算：鼠标横坐标整除单元格宽度40计算列索引
            行 = 鼠标y // 40                           # 索引换算：鼠标纵坐标整除单元格高度40计算行索引
            if 0 <= 列 < 10 and 0 <= 行 < 10:          # 边界保护：防止坐标临界值导致数组越界
                画布[行][列] = 当前颜色索引            # 单元格填色：将当前选中的画笔颜色编号写入数组
        else:                                          # 新增代码：底部调色盘点击选色逻辑(鼠标y >= 400)
            当前颜色索引 = min(4, max(0, 鼠标x // 80)) # 新增代码：按横坐标区间切换颜色(400像素分为5块，每块80像素)

    窗口.fill((200, 200, 200))                         # 浅灰色背景：充当网格间隙与底部分割线外框

    for 行 in range(10):                               # 嵌套循环：遍历二维画布的所有行与列
        for 列 in range(10):
            颜色 = 调色盘颜色[画布[行][列]]            # 根据当前格子的颜色编号提取RGB颜色元组
            pygame.draw.rect(窗口, 颜色, (列 * 40 + 2, 行 * 40 + 2, 36, 36))  # 绘制带2像素外边框的36x36像素格点

    for 编号, 色块颜色 in enumerate(调色盘颜色):        # 新增代码：遍历绘制底部的5个调色盘选色按钮
        pygame.draw.rect(窗口, 色块颜色, (编号 * 80 + 5, 410, 70, 40))         # 新增代码：绘制色块按钮(宽70, 高40)
        if 编号 == 当前颜色索引:                       # 新增代码：当前选中颜色高亮金黄色加粗外边框
            pygame.draw.rect(窗口, (255, 215, 0), (编号 * 80 + 5, 410, 70, 40), 3)

    pygame.display.flip()                              # 双缓冲刷新：将新绘制的画面一次性呈现到屏幕
    时钟.tick(60)                                      # 锁定帧率：稳定每秒60帧流畅运行

pygame.quit()
