import pygame, random

pygame.init()
窗口 = pygame.display.set_mode((400, 500))
pygame.display.set_caption("Flappy Bird - Lesson 3")
时钟 = pygame.time.Clock()
字体 = pygame.font.Font(None, 36)                     # 新增变量：纯内置默认字体(是什么)，避免跨平台字体报错(为什么)，字号36(怎么用)

小鸟x = 60                                             # 小鸟水平固定横坐标
小鸟y = 250.0                                         # 小鸟垂直当前高度
速度y = 0.0                                           # 小鸟垂直移动速度
管道列表 = []                                          # 存储管道数据列表[[x, 间隙上边缘y, 是否已计分], ...]
得分 = 0                                              # 新增变量：成功穿越障碍的累计得分
游戏结束 = False                                      # 新增变量：标记当前是否发生坠地或撞管死亡
运行中 = True

while 运行中:
    for 事件 in pygame.event.get():
        if 事件.type == pygame.QUIT:
            运行中 = False
        if 事件.type == pygame.KEYDOWN and 事件.key == pygame.K_SPACE:
            if 游戏结束:                               # 新增代码：死亡后按空格键重开新局
                小鸟y = 250.0                         # 新增代码：重置小鸟高度
                速度y = 0.0                           # 新增代码：重置小鸟速度
                管道列表.clear()                      # 新增代码：清空当前管道
                得分 = 0                              # 新增代码：分数清零
                游戏结束 = False                      # 新增代码：恢复进行中状态
            else:
                速度y = -7.0                          # 空格煽动翅膀给予向上初速度

    if not 游戏结束:                                   # 新增代码：仅在未死亡时更新物理与碰撞
        速度y += 0.4                                  # 重力持续向下微增速度
        小鸟y += 速度y                                # 更新小鸟垂直高度

        if 小鸟y < 15 or 小鸟y > 485:                 # 碰顶天花板或触地坠毁判定
            游戏结束 = True

        if len(管道列表) == 0 or 管道列表[-1][0] < 220:  # 间距控制：最后一根管道前移到220时生成下一根新管道
            管道列表.append([400, random.randint(80, 280), False])

        小鸟矩形 = pygame.Rect(小鸟x - 15, int(小鸟y) - 15, 30, 30)  # 生成小鸟30x30碰撞检测包围盒

        for 索引 in range(len(管道列表) - 1, -1, -1):  # 倒序遍历管道列表移动与检测
            管道 = 管道列表[索引]
            管道[0] -= 4                              # 管道向左平移

            上管道 = pygame.Rect(管道[0], 0, 50, 管道[1])                 # 上方障碍管道矩形(宽50)
            下管道 = pygame.Rect(管道[0], 管道[1] + 120, 50, 500)         # 下方障碍管道矩形(留出120像素飞行间隙)

            if 小鸟矩形.colliderect(上管道) or 小鸟矩形.colliderect(下管道):  # 新增代码：检测小鸟是否撞击任意一根管道
                游戏结束 = True

            if not 管道[2] and 管道[0] + 50 < 小鸟x:   # 新增代码：小鸟完全越过管道右侧判定成功穿越
                得分 += 1                             # 新增代码：成功穿越加1分
                管道[2] = True

            if 管道[0] < -60:                          # 移出屏幕左侧后销毁
                管道列表.pop(索引)

    窗口.fill((100, 200, 255))                         # 蓝天背景全屏填充
    pygame.draw.circle(窗口, (255, 220, 0), (小鸟x, int(小鸟y)), 15)  # 绘制黄色圆形小鸟(半径15)

    for 管道 in 管道列表:                              # 循环绘制上下绿色障碍管道
        pygame.draw.rect(窗口, (30, 160, 50), (管道[0], 0, 50, 管道[1]))
        pygame.draw.rect(窗口, (30, 160, 50), (管道[0], 管道[1] + 120, 50, 500))

    得分画面 = 字体.render(f"SCORE: {得分}", True, (255, 255, 255))   # 新增代码：默认字体渲染纯英文得分
    窗口.blit(得分画面, (10, 10))

    if 游戏结束:
        提示画面 = 字体.render("GAME OVER - Press SPACE", True, (255, 50, 50))  # 新增代码：红色醒目英文提示失败与按空格重开
        窗口.blit(提示画面, (30, 230))                                       # 新增代码：居中贴在画面中部

    pygame.display.flip()                              # 双缓冲刷新：将新绘制的画面一次性呈现到屏幕
    时钟.tick(60)                                      # 锁定帧率：稳定每秒60帧流畅运行

pygame.quit()
