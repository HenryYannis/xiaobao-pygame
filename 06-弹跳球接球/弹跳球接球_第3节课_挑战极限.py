import pygame, random

pygame.init()
窗口 = pygame.display.set_mode((400, 400))
pygame.display.set_caption("Ball Catch - Lesson 3")
时钟 = pygame.time.Clock()
字体 = pygame.font.Font(None, 36)                     # 新增变量：纯内置默认字体(是什么)，避免跨平台字体报错(为什么)，字号36(怎么用)

球x, 球y = 200.0, 50.0                                 # 小球初始坐标(浮点数方便重力微调累加)
球速度x, 球速度y = 0.0, 2.0                           # 小球水平与垂直速度
挡板x = 160                                           # 挡板左上角横坐标
得分 = 0                                              # 新增变量：累计接球得分
游戏结束 = False                                      # 新增变量：标记当前是否处于失败结局状态
运行中 = True

while 运行中:
    for 事件 in pygame.event.get():
        if 事件.type == pygame.QUIT:
            运行中 = False
        if 游戏结束 and 事件.type == pygame.KEYDOWN and 事件.key == pygame.K_SPACE:  # 新增代码：失败后按空格键重置开始新一局
            球x, 球y = 200.0, 50.0                    # 新增代码：重置小球位置到上方中央
            球速度x, 球速度y = 0.0, 2.0               # 新增代码：重置初始下落速度
            得分 = 0                                  # 新增代码：分数清零
            游戏结束 = False                          # 新增代码：重置游戏状态为进行中

    if not 游戏结束:                                   # 新增代码：仅在游戏未结束时更新物理运动与玩家控制
        球速度y += 0.15                               # 新增代码：模拟重力加速度，每帧微增下落速度
        球x += 球速度x                                # 水平位移：累加横向速度
        球y += 球速度y                                # 垂直位移：累加纵向速度

        if 球x <= 10 or 球x >= 390:                   # 左右墙壁碰撞：球心到达边缘时横向速度取反反弹
            球速度x *= -1
        if 球y <= 10:                                 # 顶部天花板碰撞：碰到顶部强制向下运动
            球速度y = abs(球速度y)

        if 球速度y > 0 and 360 <= 球y <= 375 and 挡板x <= 球x <= 挡板x + 80:  # 挡板接球判定：球到达挡板高度且处于横向宽度80区间内；还要求球正在往下落(速度y>0)且没掉过挡板(y<=375)
            球速度y = -6                              # 弹性反弹：给球一个向上的反冲速度
            球速度x = random.randint(-4, 4)           # 随机角度：反弹时随机改变水平速度，增加接球变数
            得分 += 10                                # 新增代码：成功接球得分累加10分

        if 球y > 400:                                 # 新增代码：掉落底部判定，球漏接掉出屏幕下边缘
            游戏结束 = True                           # 新增代码：进入游戏结束状态

        按键 = pygame.key.get_pressed()               # 获取键盘连续按下状态
        if 按键[pygame.K_LEFT] and 挡板x > 0:         # 挡板左移且防止移出左边界
            挡板x -= 6
        if 按键[pygame.K_RIGHT] and 挡板x < 320:      # 挡板右移且防止移出右边界(400 - 宽度80 = 320)
            挡板x += 6

    窗口.fill((30, 30, 30))                           # 深灰黑背景：RGB颜色(30, 30, 30)全屏覆盖
    pygame.draw.circle(窗口, (255, 255, 255), (int(球x), int(球y)), 10)  # 绘制白色小球(圆心, 半径10)
    pygame.draw.rect(窗口, (0, 255, 100), (挡板x, 370, 80, 10))          # 绘制翠绿色挡板(矩形左上角, 宽80, 高10)

    得分画面 = 字体.render(f"SCORE: {得分}", True, (255, 255, 255))       # 新增代码：默认字体纯英文渲染得分图像
    窗口.blit(得分画面, (10, 10))                                         # 新增代码：贴在左上角UI位置(10, 10)

    if 游戏结束:
        提示画面 = 字体.render("GAME OVER - Press SPACE", True, (255, 0, 0)) # 新增代码：红色醒目英文提示失败并引导按空格重开
        窗口.blit(提示画面, (40, 180))                                      # 新增代码：居中贴在屏幕中央(40, 180)

    pygame.display.flip()                              # 双缓冲刷新：将新绘制的画面一次性呈现到屏幕
    时钟.tick(60)                                      # 锁定帧率：稳定每秒60帧流畅运行

pygame.quit()
